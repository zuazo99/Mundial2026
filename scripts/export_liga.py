"""Exporta las probabilidades de La Liga a web/src/data/liga.ts (módulo TypeScript tipado).

    python scripts/export_liga.py

Entradas: results/liga_probabilities.json (src/liga/simulate.py) y data/liga/df_liga.csv (src/liga/ingest.py).
La pestaña web no se actualiza sola: tras datos nuevos hay que repetir
ingest → model → simulate → export_liga y commitear el resultado.
"""
import json
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

PROB_PATH = os.path.join(ROOT, "results", "liga_probabilities.json")
LONG_PATH = os.path.join(ROOT, "data", "liga", "df_liga.csv")
OUT_PATH = os.path.join(ROOT, "web", "src", "data", "liga.ts")

# Nombre corto para la interfaz (móvil). Un club sin entrada aquí falla el test de cobertura.
SHORT_NAMES = {
    "Athletic Club": "Athletic", "CA Osasuna": "Osasuna", "Club Atlético de Madrid": "Atlético",
    "Deportivo Alavés": "Alavés", "Elche CF": "Elche", "FC Barcelona": "Barcelona", "Getafe CF": "Getafe",
    "Levante UD": "Levante", "Málaga CF": "Málaga", "RC Celta de Vigo": "Celta",
    "RC Deportivo La Coruña": "Deportivo", "RCD Espanyol de Barcelona": "Espanyol",
    "Rayo Vallecano de Madrid": "Rayo", "Real Betis Balompié": "Betis", "Real Madrid CF": "Real Madrid",
    "Real Racing Club de Santander": "Racing", "Real Sociedad de Fútbol": "Real Sociedad",
    "Sevilla FC": "Sevilla", "Valencia CF": "Valencia", "Villarreal CF": "Villarreal",
    # clubes de temporadas recientes (por si reaparecen)
    "CD Leganés": "Leganés", "Cádiz CF": "Cádiz", "Girona FC": "Girona", "Granada CF": "Granada",
    "RCD Mallorca": "Mallorca", "Real Oviedo": "Oviedo", "Real Valladolid CF": "Valladolid",
    "SD Eibar": "Eibar", "SD Huesca": "Huesca", "UD Almería": "Almería", "UD Las Palmas": "Las Palmas",
}

_TS_HEADER = """// AUTO-GENERATED by scripts/export_liga.py — do not edit manually

export interface LigaTeam {
  name: string;
  short: string;
  played: number;
  gd: number;
  form: string;            // últimos resultados, del más antiguo al más reciente (W/D/L)
  pointsNow: number;
  expPoints: number;
  expPosition: number;
  pChampion: number;
  pChampions: number;
  pEuropa: number;
  pRelegation: number;
  positionDist: number[];  // positionDist[i] = P(acabar en el puesto i+1)
}

export interface LigaMeta {
  season: string;
  seasonLabel: string;
  dataAsOf: string;
  nSims: number;
  seed: number;
  rho: number;
  strengthSigma: number;
  xgFrozen: boolean;
  zones: { champions: number; europa: [number, number]; relegation: number };
  playedMatches: number;
  pendingMatches: number;
}

export interface LigaData { meta: LigaMeta; teams: LigaTeam[]; }

"""


def short_name(team: str) -> str:
    return SHORT_NAMES.get(team, team)


def build_liga(prob: dict, long_df: pd.DataFrame) -> dict:
    """Estructura para la web a partir de la salida de simulate y del formato largo ingerido."""
    meta_in = prob["meta"]
    season = meta_in["season"]
    cur = long_df[long_df["season"] == season].copy()
    cur["date"] = pd.to_datetime(cur["date"])
    cur = cur.sort_values(["date", "team"], kind="stable")

    meta = {
        "season": season, "seasonLabel": f"20{season[:2]}/{season[2:]}", "dataAsOf": meta_in["data_as_of"],
        "nSims": int(meta_in["n_sims"]), "seed": int(meta_in["seed"]), "rho": round(float(meta_in["rho"]), 4),
        "strengthSigma": float(meta_in.get("strength_sigma", 0.0)), "xgFrozen": bool(meta_in["xg_frozen"]),
        "zones": meta_in["zones"], "playedMatches": int(meta_in["played_matches"]),
        "pendingMatches": int(meta_in["pending_matches"]),
    }
    teams = []
    for name, v in prob["teams"].items():
        rows = cur[cur["team"] == name]
        res = ["W" if g > c else ("D" if g == c else "L") for g, c in zip(rows["goals"], rows["goals_conceded"])]
        teams.append({
            "name": name, "short": short_name(name), "played": int(len(rows)),
            "gd": int((rows["goals"] - rows["goals_conceded"]).sum()), "form": "".join(res[-5:]),
            "pointsNow": int(v["points_now"]), "expPoints": round(float(v["exp_points"]), 2),
            "expPosition": round(float(v["exp_position"]), 2),
            "pChampion": round(float(v["p_champion"]), 4), "pChampions": round(float(v["p_champions"]), 4),
            "pEuropa": round(float(v["p_europa"]), 4), "pRelegation": round(float(v["p_relegation"]), 4),
            "positionDist": [round(float(x), 4) for x in v["position_dist"]],
        })
    teams.sort(key=lambda t: (t["expPosition"], t["name"]))
    return {"meta": meta, "teams": teams}


def render_ts(data: dict) -> str:
    return _TS_HEADER + "export const liga: LigaData = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"


def main(prob_path: str = PROB_PATH, long_path: str = LONG_PATH, out_path: str = OUT_PATH) -> None:
    if not (os.path.exists(prob_path) and os.path.exists(long_path)):
        raise SystemExit("Faltan resultados de La Liga. Ejecuta antes: python src/liga/ingest.py, "
                         "python src/liga/model.py y python src/liga/simulate.py")
    prob = json.load(open(prob_path, encoding="utf-8"))
    long = pd.read_csv(long_path, dtype={"season": str}, parse_dates=["date"])
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(render_ts(build_liga(prob, long)))
    print(f"✅ {out_path}")


if __name__ == "__main__":
    main()
