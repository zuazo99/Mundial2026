"""Exportador de La Liga a TypeScript (web/src/data/liga.ts)."""
import importlib.util
import json
import os

import numpy as np
import pandas as pd
import pytest

from liga import ingest, simulate as sim
from liga_synth import TEAMS, make_seasons

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_spec = importlib.util.spec_from_file_location("export_liga", os.path.join(ROOT, "scripts", "export_liga.py"))
ex = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ex)


@pytest.fixture(scope="module")
def world():
    seasons = make_seasons()
    last = list(seasons)[-1]
    long = ingest.to_long(ingest.add_elo(seasons))
    pend = ingest.pending_fixtures(seasons[last])
    pend["xg_home"], pend["xg_away"] = 1.4, 1.1
    out = sim.simulate_season(TEAMS, seasons[last][["home", "away", "hg", "ag"]], pend, -0.02, 400, 3)
    out["meta"].update(season=last, data_as_of="2025-10-05")
    return dict(prob=out, long=long, last=last, seasons=seasons)


def test_schema_and_invariants(world):
    d = ex.build_liga(world["prob"], world["long"])
    assert set(d) == {"meta", "teams"}
    m = d["meta"]
    assert m["seasonLabel"] == f"20{world['last'][:2]}/{world['last'][2:]}"
    assert m["dataAsOf"] == "2025-10-05" and m["nSims"] == 400 and m["strengthSigma"] == 0.0
    assert m["zones"] == {"champions": 4, "europa": [5, 6], "relegation": 3}
    assert len(d["teams"]) == len(TEAMS)
    assert sum(t["pChampion"] for t in d["teams"]) == pytest.approx(1.0, abs=1e-3)
    assert sum(t["pRelegation"] for t in d["teams"]) == pytest.approx(3.0, abs=1e-3)
    for t in d["teams"]:
        assert len(t["positionDist"]) == len(TEAMS)
        assert sum(t["positionDist"]) == pytest.approx(1.0, abs=2e-3)       # redondeo a 4 decimales


def test_teams_sorted_by_expected_position(world):
    pos = [t["expPosition"] for t in ex.build_liga(world["prob"], world["long"])["teams"]]
    assert pos == sorted(pos)


def test_played_and_goal_difference_come_from_current_season_matches(world):
    d = ex.build_liga(world["prob"], world["long"])
    cur = world["seasons"][world["last"]]
    for t in d["teams"]:
        home, away = cur[cur.home == t["name"]], cur[cur.away == t["name"]]
        assert t["played"] == len(home) + len(away)
        assert t["gd"] == int(home.hg.sum() + away.ag.sum() - home.ag.sum() - away.hg.sum())
        assert len(t["form"]) == min(5, t["played"]) and set(t["form"]) <= set("WDL")


def test_pointsNow_matches_simulation_input(world):
    d = ex.build_liga(world["prob"], world["long"])
    for t in d["teams"]:
        assert t["pointsNow"] == world["prob"]["teams"][t["name"]]["points_now"]


def test_ts_file_has_header_types_and_valid_json_payload(world):
    ts = ex.render_ts(ex.build_liga(world["prob"], world["long"]))
    assert ts.startswith("// AUTO-GENERATED by scripts/export_liga.py")
    assert "export interface LigaTeam" in ts and "export const liga: LigaData =" in ts
    payload = ts.split("export const liga: LigaData = ", 1)[1].rstrip().rstrip(";")
    assert json.loads(payload)["meta"]["nSims"] == 400


def test_short_names_cover_every_team_of_the_current_real_season():
    long = pd.read_csv(os.path.join(ROOT, "data", "liga", "df_liga.csv"), dtype={"season": str})
    cur = long[long["season"] == long["season"].max()]
    missing = sorted(t for t in set(cur["team"]) if t not in ex.SHORT_NAMES)
    assert not missing, f"Faltan nombres cortos para: {missing}"
    assert len(set(ex.SHORT_NAMES[t] for t in set(cur["team"]))) == len(set(cur["team"]))     # sin colisiones


def test_committed_ts_matches_regeneration_from_committed_results():
    prob = json.load(open(os.path.join(ROOT, "results", "liga_probabilities.json"), encoding="utf-8"))
    long = pd.read_csv(os.path.join(ROOT, "data", "liga", "df_liga.csv"), dtype={"season": str}, parse_dates=["date"])
    expected = ex.render_ts(ex.build_liga(prob, long))
    committed = open(os.path.join(ROOT, "web", "src", "data", "liga.ts"), encoding="utf-8").read()
    assert committed == expected, "web/src/data/liga.ts desfasado: ejecuta python scripts/export_liga.py"


